export function translate(
  lang: string,
  key: MessageKey,
  vars?: Record<string, string>,
): string {
  const raw = packs[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce(
    (s, [k, v]) => s.replaceAll(`{${k}}`, v),
    raw,
  );
}
