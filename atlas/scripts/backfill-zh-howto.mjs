function convertSteps(steps) {
  return steps.map((s) => toTw(s));
}

function prettyWrite(path, obj) {
  writeFileSync(path, JSON.stringify(obj, null, 2) + "\n", "utf8");
}

function main() {
  const curatedPath = join(dataDir, "curated-i18n.json");
  const archPath = join(dataDir, "archetypes-i18n.json");
  const curatedEn = JSON.parse(readFileSync(join(dataDir, "curated-en.json"), "utf8"));
  const archEn = JSON.parse(readFileSync(join(dataDir, "archetypes-en.json"), "utf8"));
  const curated = JSON.parse(readFileSync(curatedPath, "utf8"));
  const arch = JSON.parse(readFileSync(archPath, "utf8"));

  const curatedHant = Object.fromEntries(
    Object.entries(curatedHans).map(([id, steps]) => [id, convertSteps(steps)]),
  );
  const archetypeHant = Object.fromEntries(
    Object.entries(archetypeHans).map(([id, steps]) => [id, convertSteps(steps)]),
  );

  const stats = {
    curatedFixed: { "zh-Hans": 0, "zh-Hant": 0 },
    archetypeFixed: { "zh-Hans": 0, "zh-Hant": 0 },
    curatedGamesTouched: { "zh-Hans": new Set(), "zh-Hant": new Set() },
    archetypeTouched: { "zh-Hans": new Set(), "zh-Hant": new Set() },
    missing: [],
  };

  for (const [locale, table] of [
    ["zh-Hans", curatedHans],
    ["zh-Hant", curatedHant],
  ]) {
    const bucket = curated[locale];
    if (!bucket) continue;
    for (const [id, zhSteps] of Object.entries(table)) {
      const entry = bucket[id];
      if (!entry) {
        stats.missing.push(`${locale} curated ${id}`);
        continue;
      }
      const prev = Array.isArray(entry.howToPlay) ? entry.howToPlay : [];
      // Always install our CURRENT-English translations for listed games so
      // leftover English and broken MT Chinese both get corrected.
      let changed = 0;
      for (let i = 0; i < zhSteps.length; i++) {
        if (prev[i] !== zhSteps[i]) changed++;
      }
      if (changed || prev.length !== zhSteps.length) {
        entry.howToPlay = [...zhSteps];
        stats.curatedFixed[locale] += changed || zhSteps.length;
        stats.curatedGamesTouched[locale].add(id);
        if (entry.howToPlay.every(hasCJK) && entry.fallbackEn === true) {
          delete entry.fallbackEn;
        }
      }
    }
  }

  for (const [locale, table] of [
    ["zh-Hans", archetypeHans],
    ["zh-Hant", archetypeHant],
  ]) {
    const bucket = arch[locale];
    if (!bucket) continue;
    for (const [id, zhSteps] of Object.entries(table)) {
      const entry = bucket[id];
      if (!entry) {
        stats.missing.push(`${locale} archetype ${id}`);
        continue;
      }
      const enSteps = archEn[id]?.steps || [];
      if (zhSteps.length !== enSteps.length) {
        stats.missing.push(
          `${locale} archetype ${id} length mismatch ${zhSteps.length} vs ${enSteps.length}`,
        );
      }
      // All archetype steps were English — replace entirely
      const before = JSON.stringify(entry.steps || []);
      entry.steps = [...zhSteps];
      const after = JSON.stringify(entry.steps);
      if (before !== after) {
        stats.archetypeFixed[locale] += zhSteps.length;
        stats.archetypeTouched[locale].add(id);
        if (entry.fallbackEn === true) delete entry.fallbackEn;
      }
    }
  }

  prettyWrite(curatedPath, curated);
  prettyWrite(archPath, arch);

  // Verify
  let leftover = 0;
  const leftoverSamples = [];
  for (const locale of ["zh-Hans", "zh-Hant"]) {
    for (const [id, g] of Object.entries(curated[locale] || {})) {
      for (const s of g.howToPlay || []) {
        if (!hasCJK(s)) {
          leftover++;
          leftoverSamples.push(`${locale} curated ${id}: ${s.slice(0, 60)}`);
        }
      }
    }
    for (const [id, a] of Object.entries(arch[locale] || {})) {
      for (const s of a.steps || []) {
        if (!hasCJK(s)) {
          leftover++;
          leftoverSamples.push(`${locale} archetype ${id}: ${s.slice(0, 60)}`);
        }
      }
    }
  }

  console.log(
    JSON.stringify(
      {
        curatedStepsFixed: stats.curatedFixed,
        curatedGamesTouched: {
          "zh-Hans": [...stats.curatedGamesTouched["zh-Hans"]].sort(),
          "zh-Hant": [...stats.curatedGamesTouched["zh-Hant"]].sort(),
        },
        archetypeStepsFixed: stats.archetypeFixed,
        archetypeTouched: {
          "zh-Hans": [...stats.archetypeTouched["zh-Hans"]].sort(),
          "zh-Hant": [...stats.archetypeTouched["zh-Hant"]].sort(),
        },
        missing: stats.missing,
        leftoverEnglishSteps: leftover,
        leftoverSamples: leftoverSamples.slice(0, 20),
      },
      null,
      2,
    ),
  );

  if (leftover > 0) process.exitCode = 1;
}

main();
