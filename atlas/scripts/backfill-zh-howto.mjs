function loadOpenCC() {
  const candidates = [
    "/tmp/opencc/package",
    join(__dirname, "../node_modules/opencc-js"),
    "opencc-js",
  ];
  for (const c of candidates) {
    try {
      if (c.startsWith("/") && !existsSync(c)) continue;
      return require(c);
    } catch {
      /* try next */
    }
  }
  throw new Error("opencc-js not found; unpack to /tmp/opencc/package first");
}

