const PLACEHOLDERS = {
  "home.featuredDay": ["{date}"],
  "collection.dailyDay": ["{date}"],
  "guide.botName": [],
  "guide.botStatus": [],
  "guide.you": [],
  "guide.thinkingLabel": [],
  "guide.think.step1": [],
  "guide.think.step2": [],
  "guide.think.step3": [],
  "chat.greet.reply": [],
  "chat.greet.again": [],
  "chat.ack.soft": [],
  "chat.smalltalk.well": [],
  "chat.smalltalk.thanks": [],
  "chat.followup.chatty": [],
};

const expectedKeys = Object.keys(PLACEHOLDERS);
let patchedFiles = 0;
let added = 0;

for (const file of readdirSync(packsDir).filter((f) => f.endsWith(".json"))) {
  const code = file.replace(/\.json$/, "");
  const patch = PATCH[code];
  if (!patch) throw new Error(`No patch for locale pack ${code}`);
  for (const k of expectedKeys) {
    if (!(k in patch)) throw new Error(`${code} missing patch key ${k}`);
    for (const ph of PLACEHOLDERS[k]) {
      if (!patch[k].includes(ph)) {
        throw new Error(`${code} ${k} missing placeholder ${ph}`);
      }
    }
  }
  const path = join(packsDir, file);
  const map = JSON.parse(readFileSync(path, "utf8"));
  let localAdded = 0;
  for (const [k, v] of Object.entries(patch)) {
    if (!(k in map)) {
      map[k] = v;
      localAdded++;
      added++;
    }
  }
  if (localAdded) {
    writeFileSync(path, JSON.stringify(map, null, 2) + "\n");
    patchedFiles++;
    console.log(`patched ${code}: +${localAdded}`);
  } else {
    console.log(`ok ${code}`);
  }
}

console.log(`Done. files=${patchedFiles} keysAdded=${added}`);

