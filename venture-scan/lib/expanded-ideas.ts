type IdeaDraft = {
  slug: string;
  name: string;
  description: string;
  businessModel: string;
  teamCountry: string;
  teamCity: string;
  teamSize: number;
  industry: string;
  sector: string;
  fundraisingSecured: boolean;
  fundingStage?: string;
  fundingAmountUsd?: number;
  fundingRoundNote?: string;
  website: string;
  social: SocialAccount[];
  strategy: GoForwardStrategy;
  goForwardSummary: string;
  source: string;
  tags: string[];
};

function draftToIdea(draft: IdeaDraft, index: number): StartupIdea {
  return {
    id: `idea_${String(index + 21).padStart(2, "0")}`,
    slug: draft.slug,
    name: draft.name,
    description: draft.description,
    businessModel: draft.businessModel,
    teamCountry: draft.teamCountry,
    teamCity: draft.teamCity,
    teamSize: draft.teamSize,
    industry: draft.industry,
    sector: draft.sector,
    fundraisingSecured: draft.fundraisingSecured,
    fundingStage: draft.fundingStage,
    fundingAmountUsd: draft.fundingAmountUsd,
    fundingRoundNote: draft.fundingRoundNote,
    website: draft.website,
    social: draft.social,
    goForward: {
      strategy: draft.strategy,
      summary: draft.goForwardSummary,
    },
    source: draft.source,
    scannedAt,
    tags: draft.tags,
  };
}

