export function sourceHealth(
  source: DataSource,
  now = Date.now(),
): SourceHealth {
  if (/offline/i.test(source.notes ?? "")) {
    return "offline";
  }
  const ageMs = now - new Date(source.lastSourcedAt).getTime();
  const hour = 60 * 60 * 1000;
  if (ageMs <= 24 * hour) return "healthy";
  if (ageMs <= 7 * 24 * hour) return "degraded";
  return "stale";
}

export function allCoveredCountries(sources: DataSource[] = DATA_SOURCES): string[] {
  return [...new Set(sources.flatMap((s) => s.countries))].sort((a, b) =>
    a.localeCompare(b),
  );
}

export function sourcesSummary(now = Date.now()) {
  const healthCounts = { healthy: 0, degraded: 0, stale: 0, offline: 0 };
  for (const source of DATA_SOURCES) {
    healthCounts[sourceHealth(source, now)] += 1;
  }
  const lastSourcedAt = DATA_SOURCES.map((s) => s.lastSourcedAt).sort().at(-1) ?? null;
  return {
    total: DATA_SOURCES.length,
    countries: allCoveredCountries(),
    healthCounts,
    lastSourcedAt,
    languages: [...new Set(DATA_SOURCES.map((s) => s.language))].sort(),
  };
}
