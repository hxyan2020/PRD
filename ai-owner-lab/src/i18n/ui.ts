const catalogs: Record<Lang, Record<UiKey, string>> = { en: en as Record<UiKey, string>, zh }

export type { UiKey }

export function translate(lang: Lang, key: UiKey, vars?: Record<string, string | number>): string {
  let text = catalogs[lang][key] ?? catalogs.en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v))
    }
  }
  return text
}
