const TABLES: Record<LocaleCode, Dict> = {
  en, zh, hi, es, fr, ar, bn, pt, ru, id, de, ja, tr, vi, ko, it, th, pl, nl, uk,
};

export function t(locale: LocaleCode, key: MessageKey): string {
  return TABLES[locale]?.[key] ?? TABLES.en[key] ?? key;
}

export function assertAllLocalesHaveKeys(): string[] {
  const keys = Object.keys(en) as MessageKey[];
  const missing: string[] = [];
  for (const locale of Object.keys(TABLES) as LocaleCode[]) {
    for (const key of keys) {
      if (!TABLES[locale][key]) missing.push(`${locale}:${key}`);
    }
  }
  return missing;
}

/** Keys still identical to English (should be empty after a full translation pass). */
export function findUntranslatedKeys(): Record<string, string[]> {
  const keys = Object.keys(en) as MessageKey[];
  const out: Record<string, string[]> = {};
  for (const locale of Object.keys(TABLES) as LocaleCode[]) {
    if (locale === "en") continue;
    const same = keys.filter((k) => TABLES[locale][k] === en[k]);
    if (same.length) out[locale] = same;
  }
  return out;
}

