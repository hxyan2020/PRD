// Ensure every listed language has at least English fallback entry.
for (const lang of LANGUAGES) {
  if (!partials[lang.code]) partials[lang.code] = en
}

export function translate(code: string, key: string, vars?: Record<string, string | number>): string {
  const dict = partials[code] || en
  let text = dict[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v))
    }
  }
  return text
}
